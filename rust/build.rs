//! Embeds the catalog JSON files into the crate.
//!
//! In a checkout, `rust/data` is a symlink to the repository's `data/`
//! directory, and the published package contains a copy of it. Checkouts made
//! without symlink support fall back to `../data`.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let data_dir = [manifest_dir.join("data"), manifest_dir.join("../data")]
        .into_iter()
        .find(|dir| dir.join("orgs.json").is_file())
        .expect("aimodels catalog data not found next to the crate");
    let data_dir = data_dir
        .canonicalize()
        .expect("resolve the catalog data directory");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", data_dir.display());

    let mut out = String::from("// Generated by build.rs. Do not edit.\n\n");
    writeln!(
        out,
        "pub(crate) const ORGS: &str = {};",
        include(&data_dir.join("orgs.json"))
    )
    .unwrap();
    write_files(&mut out, "MODEL_FILES", &data_dir.join("models"));
    write_files(&mut out, "PROVIDER_FILES", &data_dir.join("providers"));

    let out_path = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR")).join("catalog_files.rs");
    fs::write(out_path, out).expect("write the generated catalog file list");
}

/// Writes a sorted `(file name, contents)` table for every `.json` file in `dir`,
/// matching the alphabetical order the JavaScript build reads them in.
fn write_files(out: &mut String, name: &str, dir: &Path) {
    let mut files: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|err| panic!("read {}: {err}", dir.display()))
        .map(|entry| entry.expect("read a catalog directory entry").path())
        .filter(|path| {
            path.extension()
                .is_some_and(|ext| ext.eq_ignore_ascii_case("json"))
        })
        .collect();
    files.sort();

    writeln!(out, "pub(crate) const {name}: &[(&str, &str)] = &[").unwrap();
    for path in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        let file_name = path.file_name().unwrap().to_string_lossy();
        writeln!(out, "    ({file_name:?}, {}),", include(path)).unwrap();
    }
    writeln!(out, "];").unwrap();
}

fn include(path: &Path) -> String {
    format!(
        "include_str!({:?})",
        path.to_str().expect("UTF-8 catalog path")
    )
}
